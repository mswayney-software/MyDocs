// Checks every shipped dependency (and every direct dev dependency) against the
// spec's allowlist, then regenerates THIRD_PARTY_LICENSES.md.
// Usage: node scripts/check-licenses.mjs        -> write file, fail on disallowed
//        node scripts/check-licenses.mjs --check -> also fail if the file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const ALLOWED = [
  /^MIT$/, /^MIT-0$/, /^ISC$/, /^0BSD$/, /^BSD-[23]-Clause$/, /^Apache-2\.0$/,
  /^OFL-1\.1$/, /^BlueOak-1\.0\.0$/, /^CC0-1\.0$/, /^Python-2\.0$/,
  // "BSD" with no clause count (older packages); Zlib approved by the maintainer for pako (15 Nov 2026).
  /^BSD$/, /^Zlib$/,
]
const isAllowedId = (id) => ALLOWED.some((re) => re.test(id.trim()))

// Test-only tools approved one by one. They never ship in the app.
const DEV_EXCEPTIONS = {
  '@axe-core/playwright': 'MPL-2.0', // accessibility scanner for the e2e tests; approved by the maintainer 15 Nov 2026
}

// Minimal SPDX expression check: "A OR B" passes if any branch passes; "A AND B" if all do.
function allowed(expr) {
  if (!expr) return false
  const e = expr.replace(/[()]/g, '')
  if (/ OR /.test(e)) return e.split(/ OR /).some(allowed)
  if (/ AND /.test(e)) return e.split(/ AND /).every(allowed)
  return isAllowedId(e)
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'))
const directDev = new Set(Object.keys(pkg.devDependencies ?? {}))

const rows = []
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path) continue
  const name = path.slice(path.lastIndexOf('node_modules/') + 13)
  const shipped = !info.dev
  if (!shipped && !(directDev.has(name) && path === `node_modules/${name}`)) continue
  let license = info.license
  if (!license && existsSync(`${path}/package.json`)) {
    const p = JSON.parse(readFileSync(`${path}/package.json`, 'utf8'))
    license = typeof p.license === 'string' ? p.license : p.license?.type
  }
  rows.push({ name, version: info.version, license: license ?? 'UNKNOWN', shipped })
}
// Bundled fonts and other non-npm assets are listed here by hand as they are added.
const extra = JSON.parse(readFileSync('scripts/extra-licenses.json', 'utf8'))
for (const e of extra) rows.push({ ...e, shipped: true })

const seen = new Set()
const unique = rows
  .filter((r) => { const k = `${r.name}@${r.version}`; return seen.has(k) ? false : seen.add(k) })
  .sort((a, b) => Number(b.shipped) - Number(a.shipped) || a.name.localeCompare(b.name))

const bad = unique.filter((r) => !allowed(r.license) && !(!r.shipped && DEV_EXCEPTIONS[r.name] === r.license))
const table = (list) => ['| Package | Version | License |', '| --- | --- | --- |',
  ...list.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`)].join('\n')

const md = `# Third-party licenses

Generated by \`npm run licenses\`. Do not edit by hand.

Allowed: MIT, BSD, Apache-2.0, ISC, SIL OFL (plus equivalent permissive licenses: MIT-0, 0BSD, BlueOak-1.0.0, CC0-1.0, Python-2.0, Zlib).

## Shipped with the app

${table(unique.filter((r) => r.shipped))}

## Development tools (not shipped)

${table(unique.filter((r) => !r.shipped))}
`

if (process.argv.includes('--check')) {
  const current = existsSync('THIRD_PARTY_LICENSES.md') ? readFileSync('THIRD_PARTY_LICENSES.md', 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') !== md) {
    console.error('THIRD_PARTY_LICENSES.md is out of date. Run `npm run licenses` and commit it.')
    process.exitCode = 1
  }
} else {
  writeFileSync('THIRD_PARTY_LICENSES.md', md)
}

if (bad.length) {
  console.error('Disallowed or unknown licenses (flag before install):')
  for (const r of bad) console.error(`  ${r.name}@${r.version}: ${r.license}`)
  process.exitCode = 1
} else {
  console.log(`License check passed: ${unique.length} packages.`)
}
